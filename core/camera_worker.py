"""
Dedicated Background Camera Worker Module.
Decouples 24/7 computer vision inference and compliance monitoring from HTTP web requests.
Runs continuous frame ingestion, detection, tracking, compliance evaluation, and alert dispatch
in dedicated background threads, providing thread-safe zero-overhead MJPEG streaming for web clients.
"""

import threading
import time
from typing import Optional, Callable, List, Generator
import cv2
import numpy as np

from core.pipeline import PPECompliancePipeline
from core.alert_manager import Incident


class CameraWorker:
    """
    Dedicated background worker thread for a PPECompliancePipeline instance.
    Runs continuous 24/7 inference, encodes annotated frames, and manages
    thread-safe frame dispatch to web streaming clients.
    """

    def __init__(
        self,
        pipeline: PPECompliancePipeline,
        target_fps: float = 25.0,
        name: str = "CameraWorker",
        jpeg_quality: int = 80,
        on_incidents: Optional[Callable[[List[Incident]], None]] = None
    ):
        self.pipeline = pipeline
        self.target_fps = max(1.0, min(60.0, target_fps))
        self.name = name
        self.jpeg_quality = jpeg_quality
        self.on_incidents = on_incidents

        self._thread: Optional[threading.Thread] = None
        self._stop_event = threading.Event()
        self._condition = threading.Condition()

        self._latest_jpeg: Optional[bytes] = None
        self._latest_frame_idx: int = 0
        self._latest_timestamp: float = 0.0
        self._is_running: bool = False
        self._error_count: int = 0

    def start(self):
        """Starts the background inference worker thread."""
        if self._is_running:
            return

        self._stop_event.clear()
        self._is_running = True
        self._thread = threading.Thread(target=self._run_loop, name=self.name, daemon=True)
        self._thread.start()

    def stop(self, timeout: float = 3.0):
        """Signals the worker thread to stop and waits for termination."""
        if not self._is_running:
            return

        self._is_running = False
        self._stop_event.set()

        # Wake up any waiting stream threads
        with self._condition:
            self._condition.notify_all()

        if self._thread is not None and self._thread.is_alive():
            self._thread.join(timeout=timeout)
        self._thread = None

    def is_running(self) -> bool:
        return self._is_running and (self._thread is not None and self._thread.is_alive())

    def get_latest_jpeg(self) -> Optional[bytes]:
        """Thread-safe retrieval of the most recently encoded frame."""
        with self._condition:
            return self._latest_jpeg

    def get_status(self) -> dict:
        """Returns worker status, frame count, and pipeline telemetry."""
        telemetry = self.pipeline.get_telemetry()
        return {
            "name": self.name,
            "running": self.is_running(),
            "frame_idx": self._latest_frame_idx,
            "last_timestamp": self._latest_timestamp,
            "pipeline": telemetry
        }

    def stream(self, client_fps: Optional[float] = None) -> Generator[bytes, None, None]:
        """
        Yields multipart MJPEG frame chunks as they are generated by the worker thread.
        Multiple web clients can consume this generator concurrently without incurring
        additional computer vision or model inference overhead.
        """
        last_yielded_idx = -1
        min_interval = 1.0 / (client_fps or self.target_fps)

        while not self._stop_event.is_set():
            jpeg_bytes = None
            with self._condition:
                # Wait until a newer frame is available or stop is requested
                while self._latest_frame_idx == last_yielded_idx and not self._stop_event.is_set():
                    self._condition.wait(timeout=0.1)

                if self._stop_event.is_set():
                    break

                jpeg_bytes = self._latest_jpeg
                last_yielded_idx = self._latest_frame_idx

            if jpeg_bytes is not None:
                yield (
                    b"--frame\r\n"
                    b"Content-Type: image/jpeg\r\n\r\n" + jpeg_bytes + b"\r\n"
                )
                time.sleep(min_interval * 0.5)
            else:
                time.sleep(0.02)

    def _run_loop(self):
        """Continuous execution loop running computer vision inference 24/7."""
        frame_interval = 1.0 / self.target_fps

        while not self._stop_event.is_set():
            cycle_start = time.time()

            try:
                # Execute full pipeline cycle
                success, frame, results, incidents = self.pipeline.process_next_frame()

                # Dispatch new incidents if callback configured
                if incidents and self.on_incidents:
                    try:
                        self.on_incidents(incidents)
                    except Exception as ex:
                        print(f"[{self.name}] Incident callback error: {ex}")

                # Encode frame to JPEG
                if frame is not None and frame.size > 0:
                    ret, buffer = cv2.imencode(
                        ".jpg",
                        frame,
                        [int(cv2.IMWRITE_JPEG_QUALITY), self.jpeg_quality]
                    )
                    if ret:
                        jpeg_bytes = buffer.tobytes()
                        with self._condition:
                            self._latest_jpeg = jpeg_bytes
                            self._latest_frame_idx += 1
                            self._latest_timestamp = time.time()
                            self._condition.notify_all()
                    self._error_count = 0
                else:
                    time.sleep(0.04)

            except Exception as e:
                self._error_count += 1
                if self._error_count <= 5 or self._error_count % 50 == 0:
                    print(f"[{self.name}] Worker pipeline exception: {e}")
                time.sleep(0.05)

            # Pace loop to match target FPS
            elapsed = time.time() - cycle_start
            sleep_time = frame_interval - elapsed
            if sleep_time > 0.001:
                time.sleep(sleep_time)

        self._is_running = False

